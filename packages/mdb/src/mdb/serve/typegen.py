"""Generate ``web/src/api/types.gen.ts`` from the pydantic view records' JSON Schema.

    python -m mdb.serve.typegen --write     # regenerate
    python -m mdb.serve.typegen --check     # exit 1 when the file is stale (also a test)
"""
from __future__ import annotations

import argparse
import json
import os
import sys
from pathlib import Path

from pydantic.json_schema import models_json_schema

from .schema import CAP_BYTES, EXPORTED, SCHEMAS, STRUCTURAL_KEYS

# ``MDB_TYPEGEN_TARGET`` redirects the file (tests and CI use it to check a regenerated copy that
# has not been written into web/ yet).
TARGET = Path(os.environ.get("MDB_TYPEGEN_TARGET") or
              Path(__file__).resolve().parents[3] / "web" / "src" / "api" / "types.gen.ts")
HEADER = """\
// GENERATED by `python -m mdb.serve.typegen --write` from mdb/serve/schema.py. Do not edit.
// A test (test_serve_api.py::test_generated_types_are_current) fails when this file is stale.
/* eslint-disable */

export interface Envelope<T> {
  schema: string;
  state: "resolved" | "unresolved" | "refused";
  reason?: string | null;
  data: T;
  digest: string;
  bytes: number;
  omitted?: Omitted[] | null;
}
"""


def _ts(schema, defs) -> str:
    if "$ref" in schema:
        return schema["$ref"].rsplit("/", 1)[-1]
    if "const" in schema:
        return json.dumps(schema["const"])
    if "enum" in schema:
        return " | ".join(json.dumps(v) for v in schema["enum"])
    for key in ("anyOf", "oneOf"):
        if key in schema:
            parts = list(dict.fromkeys(_ts(s, defs) for s in schema[key]))
            return " | ".join(parts)
    kind = schema.get("type")
    if isinstance(kind, list):
        return " | ".join(_ts({**schema, "type": k}, defs) for k in kind)
    if kind == "string":
        return "string"
    if kind in ("integer", "number"):
        return "number"
    if kind == "boolean":
        return "boolean"
    if kind == "null":
        return "null"
    if kind == "array":
        if "prefixItems" in schema:
            return "[" + ", ".join(_ts(s, defs) for s in schema["prefixItems"]) + "]"
        inner = _ts(schema.get("items", {}), defs)
        return f"({inner})[]" if "|" in inner else f"{inner}[]"
    if kind == "object":
        extra = schema.get("additionalProperties")
        if isinstance(extra, dict):
            return f"Record<string, {_ts(extra, defs)}>"
        return "Record<string, unknown>"
    return "unknown"


def _interface(name, schema, defs) -> str:
    required = set(schema.get("required", []))
    lines = [f"export interface {name} {{"]
    for field, sub in schema.get("properties", {}).items():
        optional = "" if field in required else "?"
        lines.append(f"  {field}{optional}: {_ts(sub, defs)};")
    lines.append("}")
    return "\n".join(lines)


def render() -> str:
    _, top = models_json_schema([(m, "serialization") for m in EXPORTED],
                                ref_template="#/$defs/{model}")
    defs = top.get("$defs", {})
    blocks = [HEADER]
    for name in sorted(defs):
        schema = defs[name]
        if schema.get("type") == "object" or "properties" in schema:
            blocks.append(_interface(name, schema, defs))
        else:
            blocks.append(f"export type {name} = {_ts(schema, defs)};")
    blocks.append("export type PointerSpec = SlotPointer | BlobPointer | OccurrencePointer;")
    blocks.append("export type ReduceResult =\n  | StatsResult\n  | TopkResult\n  | SliceResult\n"
                  "  | HistogramResult\n  | TileResult\n  | ProjectResult;")
    blocks.append("export type Ev = Num['ev'];")
    blocks.append(f"export const CAP_BYTES = {CAP_BYTES};")
    keys = ", ".join(json.dumps(k) for k in STRUCTURAL_KEYS)
    blocks.append("// Keys whose own value is structure (an int or a list of ints), never a "
                  "measurement:\n"
                  "// everything else numeric is a Num/NumList with an evidence class.\n"
                  f"export const STRUCTURAL_KEYS: readonly string[] = [{keys}];")
    schemas = ",\n".join(f"  {k if k.isidentifier() else json.dumps(k)}: {json.dumps(v)}"
                          for k, v in SCHEMAS.items())
    blocks.append(f"export const SCHEMAS = {{\n{schemas},\n}} as const;")
    return "\n\n".join(blocks) + "\n"


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    group = parser.add_mutually_exclusive_group(required=True)
    group.add_argument("--write", action="store_true")
    group.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)
    text = render()
    if args.write:
        TARGET.parent.mkdir(parents=True, exist_ok=True)
        TARGET.write_text(text)
        print(f"wrote {TARGET}")
        return 0
    current = TARGET.read_text() if TARGET.is_file() else ""
    if current != text:
        print(f"{TARGET} is stale; run python -m mdb.serve.typegen --write", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
