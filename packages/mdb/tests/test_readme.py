"""The README's verb and port tables are generated from the code and must match it.

``python tests/test_readme.py`` rewrites both generated blocks of ``README.md`` in place (the
port table needs torch); the tests fail whenever the registry or the port program changes and
the README was not regenerated, and name any registered verb missing from the README.
"""

from __future__ import annotations

from pathlib import Path

import pytest

README = Path(__file__).resolve().parents[1] / "README.md"
MAX_LINES = 400


def _cell(text: str) -> str:
    return text.replace("|", "\\|")


def verb_table() -> str:
    """One row per registered op, sorted by name: verb, usage, effect, summary."""
    from mdb.ops import registry

    rows = ["| Verb | Usage | Effect | What it does |", "|---|---|---|---|"]
    for name, op in sorted(registry().items()):
        effect = f"not built yet ({op.milestone})" if op.milestone else op.effect
        rows.append(
            f"| `{name}` | `{_cell(op.usage or name)}` | {effect} | {_cell(op.summary)} |"
        )
    return "\n".join(rows)


def _where(spec) -> str:
    site = f"`{spec.site}`" if spec.site else "decoder layer"
    return {
        "pre": f"{site} input",
        "out": f"{site} output",
        "eager-arg": "eager attention argument",
        "eager-replica": "replica from `qr`, `kr` and the mask",
        "eager-out": "eager attention weights",
    }[spec.hook]


def port_table() -> str:
    """One row per port in Qwen3 execution order; Qwen2 operator text where Qwen2 has the port
    (``qn`` and ``kn`` exist only on Qwen3)."""
    from mdb.engine.ports import program_for

    qwen2, qwen3 = program_for("qwen2"), program_for("qwen3")
    rows = ["| Port | Read at | Operator | Proofs |", "|---|---|---|---|"]
    for spec in qwen3.ports:
        own = qwen2.spec(spec.name) if spec.name in qwen2.names else spec
        label = f"`{spec.name}`" + ("" if spec.name in qwen2.names else " (Qwen3)")
        rows.append(
            f"| {label} | {_where(own)} | {_cell(own.operator)} | {' '.join(own.proofs)} |"
        )
    return "\n".join(rows)


BLOCKS = {"verbs": verb_table, "ports": port_table}


def _markers(name: str) -> tuple[str, str]:
    return (f"<!-- BEGIN {name}: generated by tests/test_readme.py -->",
            f"<!-- END {name} -->")


def block(text: str, name: str) -> str:
    begin, end = _markers(name)
    assert text.count(begin) == 1 and text.count(end) == 1, f"README needs one {name} block"
    return text.split(begin, 1)[1].split(end, 1)[0].strip("\n")


def rewrite(text: str) -> str:
    for name, render in BLOCKS.items():
        begin, end = _markers(name)
        head, rest = text.split(begin, 1)
        text = f"{head}{begin}\n{render()}\n{end}{rest.split(end, 1)[1]}"
    return text


def test_every_registered_verb_is_in_the_readme_verb_table():
    from mdb.ops import registry

    table = block(README.read_text(), "verbs")
    missing = [name for name in sorted(registry()) if f"| `{name}` |" not in table]
    assert not missing, f"verbs missing from README.md (run python tests/test_readme.py): {missing}"


def test_readme_verb_table_is_the_generated_one():
    assert block(README.read_text(), "verbs") == verb_table()


def test_readme_port_table_is_the_port_program():
    pytest.importorskip("torch")
    assert block(README.read_text(), "ports") == port_table()


def test_readme_stays_short():
    assert len(README.read_text().splitlines()) < MAX_LINES


if __name__ == "__main__":
    README.write_text(rewrite(README.read_text()))
